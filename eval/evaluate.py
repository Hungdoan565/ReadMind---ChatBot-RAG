"""
RAGAS evaluation module for the RAG Chatbot.

Metrics evaluated:
  - faithfulness      : Are claims in the answer grounded in the retrieved context?
  - answer_relevancy  : Is the answer relevant to the question?
  - context_precision : Are the retrieved docs actually useful for the question?

Usage (standalone script):
    python eval/evaluate.py --input eval/sample_questions.json

Usage (from Python):
    from eval.evaluate import run_evaluation
    results = run_evaluation(qa_pairs)

JSON input format:
    [
      {
        "question": "What is RAG?",
        "ground_truth": "RAG stands for Retrieval-Augmented Generation ..."
      },
      ...
    ]
"""

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any

# Add backend to sys.path so we can import app modules
ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "backend"))

logger = logging.getLogger(__name__)


def _build_ragas_dataset(
    qa_pairs: List[Dict[str, str]],
) -> Any:
    """
    Run the RAG chain on each question and build a RAGAS EvaluationDataset.

    Each sample requires:
      - question        (str)
      - answer          (str)  — generated by our RAG chain
      - contexts        (List[str])  — retrieved chunks
      - ground_truth    (str)  — expected answer (optional for some metrics)
    """
    from app.core.rag.chain import get_rag_chain
    from app.core.vectordb.store import hybrid_search
    from ragas import EvaluationDataset, SingleTurnSample

    rag_chain = get_rag_chain()
    samples = []

    for i, pair in enumerate(qa_pairs):
        question = pair["question"]
        ground_truth = pair.get("ground_truth", "")

        logger.info(f"Evaluating [{i + 1}/{len(qa_pairs)}]: {question[:60]}...")

        try:
            # Generate answer via our chain (fresh session per question)
            import uuid

            session_id = f"eval-{uuid.uuid4()}"
            answer: str = rag_chain.invoke(
                {"input": question},
                config={"configurable": {"session_id": session_id}},
            )

            # Retrieve contexts (same hybrid search used by chain)
            from app.config import settings

            docs = hybrid_search(question, k=settings.RETRIEVAL_TOP_K)
            contexts = [doc.page_content for doc in docs]

            sample = SingleTurnSample(
                user_input=question,
                response=answer,
                retrieved_contexts=contexts,
                reference=ground_truth or None,
            )
            samples.append(sample)

        except Exception as e:
            logger.error(f"  Failed for question '{question[:40]}...': {e}")

    return EvaluationDataset(samples=samples)


def run_evaluation(
    qa_pairs: List[Dict[str, str]],
    metrics: List[str] | None = None,
) -> Dict[str, Any]:
    """
    Run RAGAS evaluation on a list of QA pairs.

    Args:
        qa_pairs: List of {"question": ..., "ground_truth": ...} dicts.
        metrics: Which metrics to run. Defaults to all three core metrics.

    Returns:
        Dict with metric names as keys and float scores as values,
        plus "sample_count" and "errors".
    """
    from ragas import evaluate
    from ragas.metrics import faithfulness, answer_relevancy, context_precision
    from langchain_openai import ChatOpenAI, OpenAIEmbeddings
    from ragas.llms import LangchainLLMWrapper
    from ragas.embeddings import LangchainEmbeddingsWrapper
    from app.config import settings

    # Metric registry
    metric_registry = {
        "faithfulness": faithfulness,
        "answer_relevancy": answer_relevancy,
        "context_precision": context_precision,
    }

    selected_metric_names = metrics or list(metric_registry.keys())
    selected_metrics = [
        metric_registry[m] for m in selected_metric_names if m in metric_registry
    ]

    # Configure RAGAS to use same LLM/embeddings as the app
    llm = LangchainLLMWrapper(
        ChatOpenAI(
            model=settings.LLM_MODEL,
            temperature=0,
            openai_api_key=settings.OPENAI_API_KEY,
        )
    )
    embeddings = LangchainEmbeddingsWrapper(
        OpenAIEmbeddings(
            model=settings.EMBEDDING_MODEL,
            openai_api_key=settings.OPENAI_API_KEY,
        )
    )

    for metric in selected_metrics:
        metric.llm = llm
        if hasattr(metric, "embeddings"):
            metric.embeddings = embeddings

    # Build dataset
    logger.info(f"Building evaluation dataset for {len(qa_pairs)} questions...")
    dataset = _build_ragas_dataset(qa_pairs)

    if len(dataset.samples) == 0:
        return {"error": "No valid samples to evaluate", "sample_count": 0}

    # Run evaluation
    logger.info(f"Running RAGAS evaluation ({selected_metric_names})...")
    result = evaluate(dataset=dataset, metrics=selected_metrics)

    scores = result.to_pandas().mean(numeric_only=True).to_dict()
    output = {
        "sample_count": len(dataset.samples),
        "metrics": {
            k: round(float(v), 4)
            for k, v in scores.items()
            if k in selected_metric_names
        },
    }

    # Quality thresholds (from research: faithfulness >=0.9, context_precision >=0.75)
    thresholds = {
        "faithfulness": 0.9,
        "answer_relevancy": 0.8,
        "context_precision": 0.75,
    }
    output["passed"] = {
        m: output["metrics"].get(m, 0) >= thresholds.get(m, 0.0)
        for m in selected_metric_names
    }

    return output


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------


def _cli():
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(message)s",
    )

    parser = argparse.ArgumentParser(
        description="Run RAGAS evaluation on the RAG chatbot"
    )
    parser.add_argument(
        "--input",
        "-i",
        default=str(ROOT / "eval" / "sample_questions.json"),
        help="Path to JSON file with QA pairs",
    )
    parser.add_argument(
        "--output",
        "-o",
        default=None,
        help="Optional: save results to JSON file",
    )
    parser.add_argument(
        "--metrics",
        "-m",
        nargs="+",
        default=None,
        choices=["faithfulness", "answer_relevancy", "context_precision"],
        help="Which metrics to evaluate (default: all)",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    if not input_path.exists():
        print(f"[ERROR] Input file not found: {input_path}")
        sys.exit(1)

    qa_pairs = json.loads(input_path.read_text(encoding="utf-8"))
    print(f"Loaded {len(qa_pairs)} QA pairs from {input_path}")

    results = run_evaluation(qa_pairs, metrics=args.metrics)

    print("\n=== RAGAS Evaluation Results ===")
    print(f"Sample count : {results.get('sample_count', 0)}")
    if "metrics" in results:
        print("\nScores:")
        for metric, score in results["metrics"].items():
            status = "PASS" if results["passed"].get(metric, False) else "FAIL"
            print(f"  {metric:<25} {score:.4f}  [{status}]")
    else:
        print(f"Error: {results.get('error', 'unknown')}")

    if args.output:
        out_path = Path(args.output)
        out_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
        print(f"\nResults saved to {out_path}")

    return results


if __name__ == "__main__":
    _cli()
